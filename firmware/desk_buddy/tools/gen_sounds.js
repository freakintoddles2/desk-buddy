#!/usr/bin/env node
// The device's default sounds, generated from the sound lab so the two never drift.
// Reads ../../../sound-lab.html (its CATALOG and each EVENTS entry's `def` and `suggest`) and writes
// src/sound_data.h: each event's choices (its suggestions plus the default), and the same
// labels and names into display.html (Settings > Sound > Sounds).
// Usage: node tools/gen_sounds.js   (from firmware/desk_buddy, after changing a default in the lab)
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const html = fs.readFileSync(path.resolve(root, "../../sound-lab.html"), "utf8");
const script = html.split("<script>")[1].split("</script>")[0];
// The sound helpers, the catalog and the events: plain data, no DOM.
const start = script.indexOf("const T = (f, ms)");
const evAt = script.indexOf("const EVENTS = [");
const end = script.indexOf("];", evAt) + 2;
if (start < 0 || evAt < 0) throw new Error("sound-lab.html changed shape: CATALOG/EVENTS not found");
const { CATALOG, EVENTS } = new Function(script.slice(start, end) + "\nreturn { CATALOG, EVENTS };")();

const byId = Object.fromEntries(CATALOG.map((s) => [s.id, s]));
const DYNAMIC = new Set(["q_result_speed"]);  // the firmware sets the pitch itself (reflex speed)
const CATS = [...new Set(CATALOG.map((s) => s.cat))];
const idx = (id) => (id && byId[id] ? CATALOG.findIndex((s) => s.id === id) : -1);
// Each event's suggestions, with the default first if it isn't among them.
const choicesOf = (e) => {
  const list = [...e.suggest];
  if (!list.includes(e.def)) list.unshift(e.def);
  return list.map((id) => (id && byId[id] ? id : null)).filter((id, i, a) => a.indexOf(id) === i);
};
const q = (t) => `"${String(t).normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^\x20-\x7e]/g, "?").replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;  // the device fonts are ASCII only
const lines = [
  "// Generated by tools/gen_sounds.js from sound-lab.html (CATALOG, and EVENTS def/suggest). Do not edit.",
  "#pragma once",
  "#include \"buzzer.h\"",
  "",
  "namespace sounds {",
  "",
  "// One entry per sound-lab event, in the lab's order. Picks are saved by the ids in EVENT_IDS",
  "// and SOUNDS, so reordering is safe; removing or renaming an id resets that pick to the default.",
  "enum Event : uint8_t {",
  ...EVENTS.map((e) => `  ${e.id.toUpperCase()},`),
  "  EVENT_COUNT",
  "};",
  "",
  "struct Sound {",
  "  const char *id;              // the sound lab's id",
  "  const char *name;",
  "  uint8_t cat;                 // index into CATEGORIES",
  "  const buzzer::Step *steps;",
  "  uint16_t n;",
  "  uint8_t repeat;",
  "  uint16_t gap;",
  "  bool soft;                   // one volume step below the setting",
  "  bool dynamic;                // the firmware picks the pitch (reflex time)",
  "};",
  "",
  "struct EventInfo {",
  "  const char *id, *label;",
  "  int16_t def;                 // index into SOUNDS, -1 = no sound",
  "  const int16_t *suggest;      // indexes into SOUNDS, -1 = no sound",
  "  uint8_t nSuggest;",
  "};",
  "",
  `constexpr int CATEGORY_COUNT = ${CATS.length};`,
  `static const char *const CATEGORIES[CATEGORY_COUNT] = {${CATS.map(q).join(", ")}};`,
  "",
];
CATALOG.forEach((s, i) => {
  const steps = s.steps.map((st) => (st.kind === "rest" ? "{0, 0, " + st.ms + "}" : `{${st.f0}, ${st.kind === "slide" ? st.f1 : st.f0}, ${st.ms}}`));
  lines.push(`static const buzzer::Step ST_${i}[] = {${steps.join(", ")}};  // ${s.name.replace(/[^\x20-\x7e]/g, "?")}`);
});
lines.push("", `constexpr int SOUND_COUNT = ${CATALOG.length};`, "static const Sound SOUNDS[SOUND_COUNT] = {");
CATALOG.forEach((s, i) => {
  lines.push(`  {${q(s.id)}, ${q(s.name)}, ${CATS.indexOf(s.cat)}, ST_${i}, ${s.steps.length}, ${s.repeat || 1}, ${s.gap || 0}, ${s.soft ? "true" : "false"}, ${DYNAMIC.has(s.id) ? "true" : "false"}},`);
});
lines.push("};", "");
EVENTS.forEach((e) => lines.push(`static const int16_t SUG_${e.id.toUpperCase()}[] = {${choicesOf(e).map(idx).join(", ")}};`));
lines.push("", "static const EventInfo EVENTS[EVENT_COUNT] = {");
EVENTS.forEach((e) => {
  const n = choicesOf(e).length;
  lines.push(`  {${q(e.id)}, ${q(e.label)}, ${idx(e.def)}, SUG_${e.id.toUpperCase()}, ${n}},`);
});
lines.push("};", "", "}  // namespace sounds", "");
fs.writeFileSync(path.join(root, "src/sound_data.h"), lines.join("\n"));

// The faux display's Settings > Sound > Sounds: the same events, suggestions and library, written
// between its SOUND_CHOICES markers.
const faux = path.resolve(root, "../../display.html");
const fhtml = fs.readFileSync(faux, "utf8");
const data = {
  cats: CATS,
  sounds: CATALOG.map((s) => [s.name, CATS.indexOf(s.cat)]),
  events: EVENTS.map((e) => [e.label, choicesOf(e).map(idx), idx(e.def)]),  // [label, suggested (-1 = none), default]
};
const re = /(\/\/ SOUND_CHOICES begin\n)[\s\S]*?([ \t]*\/\/ SOUND_CHOICES end)/;
if (!re.test(fhtml)) throw new Error("display.html: SOUND_CHOICES markers not found");
fs.writeFileSync(faux, fhtml.replace(re, `$1    const SOUND_CHOICES = ${JSON.stringify(data)};\n$2`));
console.log(`sound_data.h: ${EVENTS.length} events, ${CATALOG.length} sounds, ${CATALOG.reduce((a, s) => a + s.steps.length, 0)} steps`);
