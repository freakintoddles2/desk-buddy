#!/usr/bin/env python3
"""Render the Home face's sun and moon (with their glows) to LVGL ARGB8888 images.

Matches display.html's Sun ring (viewBox 0 0 100 100 on a 480 px screen, so 1 unit = 4.8 px):
  sun:  r 3.6, radial fill #fff7d6 -> #ffd36b (55%) -> #ffb03a,
        drop-shadow 0 0 1.5 rgba(255,200,90,.9) and 0 0 5 rgba(255,190,80,.5)
  moon: crescent r 3.3 (outer circle minus an ellipse rx .62r), rotated -20 deg, fill #f1edd8,
        drop-shadow 0 0 2 rgba(220,220,255,.55)
Writes src/sprites.c and src/sprites.h.
"""
import math
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
U = 4.8   # px per viewBox unit
SS = 4    # supersampling


def blank(size):
    return Image.new("RGBA", (size, size), (0, 0, 0, 0))


def glow(alpha, rgb, opacity, blur_units, size):
    # CSS drop-shadow blur is a std-dev of blur/2.
    a = alpha.filter(ImageFilter.GaussianBlur(blur_units * U / 2))
    a = a.point(lambda v: round(v * opacity))
    layer = Image.new("RGBA", (size, size), rgb + (0,))
    layer.putalpha(a)
    return layer


def sun():
    size = 96
    r = 3.6 * U
    big = size * SS
    mask = Image.new("L", (big, big), 0)
    c = big / 2
    ImageDraw.Draw(mask).ellipse((c - r * SS, c - r * SS, c + r * SS, c + r * SS), fill=255)
    mask = mask.resize((size, size), Image.LANCZOS)
    # radial gradient fill
    fill = blank(size)
    stops = [(0, (0xFF, 0xF7, 0xD6)), (0.55, (0xFF, 0xD3, 0x6B)), (1, (0xFF, 0xB0, 0x3A))]
    px = fill.load()
    for y in range(size):
        for x in range(size):
            t = min(1, math.hypot(x + 0.5 - size / 2, y + 0.5 - size / 2) / r)
            for (t0, c0), (t1, c1) in zip(stops, stops[1:]):
                if t <= t1:
                    k = (t - t0) / (t1 - t0)
                    px[x, y] = tuple(round(c0[i] + (c1[i] - c0[i]) * k) for i in range(3)) + (255,)
                    break
    fill.putalpha(mask)
    out = blank(size)
    out = Image.alpha_composite(out, glow(mask, (255, 190, 80), 0.5, 5, size))
    out = Image.alpha_composite(out, glow(mask, (255, 200, 90), 0.9, 1.5, size))
    return Image.alpha_composite(out, fill)


def moon():
    size = 72
    r = 3.3 * U
    big = size * SS
    c = big / 2
    R = r * SS
    outer = Image.new("L", (big, big), 0)
    inner = Image.new("L", (big, big), 0)
    ImageDraw.Draw(outer).ellipse((c - R, c - R, c + R, c + R), fill=255)
    # Inner ellipse (rx .62r) centered on the same point; the crescent is the left half of the
    # circle outside the ellipse's left half, i.e. (circle minus ellipse) on the left side.
    ImageDraw.Draw(inner).ellipse((c - 0.62 * R, c - R, c + 0.62 * R, c + R), fill=255)
    left = Image.new("L", (big, big), 0)
    ImageDraw.Draw(left).rectangle((0, 0, c, big), fill=255)
    cres = ImageChops.multiply(ImageChops.subtract(outer, inner), left)
    cres = cres.rotate(20, resample=Image.BICUBIC, center=(c, c))  # PIL rotates counter-clockwise
    mask = cres.resize((size, size), Image.LANCZOS)
    fill = Image.new("RGBA", (size, size), (0xF1, 0xED, 0xD8, 0))
    fill.putalpha(mask)
    out = Image.alpha_composite(blank(size), glow(mask, (220, 220, 255), 0.55, 2, size))
    return Image.alpha_composite(out, fill)


def emit(name, img):
    w, h = img.size
    rgba = img.tobytes()
    data = bytearray(len(rgba))
    data[0::4], data[1::4], data[2::4], data[3::4] = rgba[2::4], rgba[1::4], rgba[0::4], rgba[3::4]  # LVGL ARGB8888 is stored B, G, R, A
    rows = [", ".join(f"0x{v:02x}" for v in data[i:i + 32]) for i in range(0, len(data), 32)]
    return (f"static const uint8_t {name}_map[] = {{\n  " + ",\n  ".join(rows) + "\n};\n"
            f"const lv_image_dsc_t {name} = {{\n"
            f"  .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, .flags = 0, .w = {w}, .h = {h}, .stride = {w * 4} }},\n"
            f"  .data_size = sizeof({name}_map),\n  .data = {name}_map,\n}};\n")


def main():
    s, m = sun(), moon()
    c = ["/* Generated by tools/gen_sprites.py. Do not edit. */", '#include "sprites.h"', "",
         emit("sprite_sun", s), emit("sprite_moon", m)]
    (ROOT / "src" / "sprites.c").write_text("\n".join(c))
    (ROOT / "src" / "sprites.h").write_text(
        "/* Generated by tools/gen_sprites.py. Do not edit. */\n#pragma once\n#include <lvgl.h>\n\n"
        "extern const lv_image_dsc_t sprite_sun;\nextern const lv_image_dsc_t sprite_moon;\n")
    prev = Image.new("RGBA", (s.width + m.width + 16, s.height), (0x0B, 0x0D, 0x11, 255))
    prev.alpha_composite(s, (0, 0))
    prev.alpha_composite(m, (s.width + 16, (s.height - m.height) // 2))
    prev.resize((prev.width * 3, prev.height * 3), Image.NEAREST).save(ROOT / "tools" / "sprites_preview.png")
    print(f"sun {s.size}, moon {m.size}")


if __name__ == "__main__":
    main()
