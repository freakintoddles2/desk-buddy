#!/usr/bin/env python3
"""Alpha masks for the fast travel tray (option D in ../../../mockups/fasttravel-mockups.html).

The tray draws straight into the framebuffer (LVGL would redraw the whole screen per frame),
so everything it shows comes from these precomputed A8 masks, scaled at run time:
  - each panel icon, from the same SVGs as gen_icons.py, at the tray's largest size
    (82% of a 144 px box, stroke .36 viewBox units, like the mock-up);
  - a soft glow per icon (the mock-up's drop-shadow, 0 0 12px at 340 px -> ~8.5 px sigma
    at 480), stored at half resolution since it's blurry anyway;
  - each panel name in Montserrat Medium (the font LVGL's built-ins use).

Usage: python3 tools/gen_tray.py   (writes src/tray_assets.c and src/tray_assets.h)
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

sys.argv = sys.argv[:1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_icons as gi  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ICON = 120          # glyph size at scale 1 (0.82 x 144 rounded up to an even number)
GLOW_PAD = 30       # room for the glow around the glyph
GLOW_SIGMA = 8.5
GLOW_HALF = (ICON + 2 * GLOW_PAD) // 2
NAME_PX = 42
NAMES = {"home": "Home", "world": "World", "weather": "Weather", "focus": "Focus", "timers": "Timers",
         "breathe": "Breathe", "habits": "Habits", "countdowns": "Days", "play": "Play",
         "settings": "Settings"}


def icon_mask(svg):
    gi.SIZE = ICON
    gi.STROKE = 0.36
    return gi.render(svg)


def knob_fill(svg):
    """Where the icon's knobs (Settings' slider dots) are filled with the screen color."""
    gi.SIZE = ICON
    c = gi.Canvas()
    for tag in gi.re.findall(r"<circle[^>]*>", svg):
        a = gi.attrs(tag)
        if "knob" in a.get("class", ""):
            c.fill_poly(c.ellipse_pts(gi.num(a, "cx"), gi.num(a, "cy"), gi.num(a, "r"), gi.num(a, "r")), 255)
    return c.img.resize((ICON, ICON), Image.LANCZOS)


def glow_mask(icon, svg):
    full = Image.new("L", (ICON + 2 * GLOW_PAD,) * 2, 0)
    full.paste(icon, (GLOW_PAD, GLOW_PAD))
    blurred = full.filter(ImageFilter.GaussianBlur(GLOW_SIGMA))
    # Normalize so the brightest glow is full alpha; the firmware applies the strength.
    mx = blurred.getextrema()[1] or 1
    blurred = blurred.point(lambda v: min(255, round(v * 255 / mx)))
    # The knobs are opaque in the mock-up, so no glow shows inside them.
    hole = Image.new("L", blurred.size, 0)
    hole.paste(knob_fill(svg), (GLOW_PAD, GLOW_PAD))
    blurred = Image.composite(Image.new("L", blurred.size, 0), blurred, hole)
    return blurred.resize((GLOW_HALF, GLOW_HALF), Image.LANCZOS)


def name_mask(text, font, asc, desc):
    w = int(font.getlength(text)) + 4
    h = asc + desc
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((2, asc), text, font=font, fill=255, anchor="ls")
    return img


def c_array(name, img):
    data = img.tobytes()
    w, h = img.size
    rows = [", ".join(str(b) for b in data[r * w:(r + 1) * w]) for r in range(h)]
    return [f"static const uint8_t {name}_px[] = {{"] + [f"  {r}," for r in rows] + ["};"]


def main():
    svgs = gi.icon_svgs()
    font = ImageFont.truetype(str(ROOT / "tools" / "fonts" / "Montserrat-Medium.ttf"), NAME_PX)
    asc, desc = font.getmetrics()
    out = ["/* Generated by tools/gen_tray.py. Do not edit. */", '#include "tray_assets.h"', ""]
    table = []
    preview = []
    for pid, svg in svgs.items():
        ic = icon_mask(svg)
        gl = glow_mask(ic, svg)
        nm = name_mask(NAMES[pid], font, asc, desc)
        out += c_array(f"tray_icon_{pid}", ic)
        out += c_array(f"tray_glow_{pid}", gl)
        out += c_array(f"tray_name_{pid}", nm)
        table.append(f'  {{"{pid}", tray_icon_{pid}_px, tray_glow_{pid}_px, tray_name_{pid}_px, {nm.size[0]}}},')
        preview.append((ic, gl, nm))
    out += ["", "const TrayAsset TRAY_ASSETS[] = {"] + table + ["};",
            f"const int TRAY_ASSET_COUNT = {len(table)};", ""]
    (ROOT / "src" / "tray_assets.c").write_text("\n".join(out))
    (ROOT / "src" / "tray_assets.h").write_text("\n".join([
        "/* Generated by tools/gen_tray.py. Do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define TRAY_ICON {ICON}            /* icon mask: TRAY_ICON x TRAY_ICON, A8 */",
        f"#define TRAY_GLOW_PAD {GLOW_PAD}",
        f"#define TRAY_GLOW_HALF {GLOW_HALF}  /* glow mask: half resolution, covers the icon + pad */",
        f"#define TRAY_NAME_H {asc + desc}     /* name masks: width per asset x TRAY_NAME_H */",
        f"#define TRAY_NAME_ASC {asc}",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "typedef struct {",
        "  const char *id;",
        "  const uint8_t *icon;",
        "  const uint8_t *glow;",
        "  const uint8_t *name;",
        "  int nameW;",
        "} TrayAsset;",
        "extern const TrayAsset TRAY_ASSETS[];",
        "extern const int TRAY_ASSET_COUNT;",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
    ]))
    # Preview for eyeballing.
    sheet = Image.new("L", (len(preview) * (ICON + 2 * GLOW_PAD + 8), ICON + 2 * GLOW_PAD + 60), 0)
    for k, (ic, gl, nm) in enumerate(preview):
        x = k * (ICON + 2 * GLOW_PAD + 8)
        g = gl.resize((ICON + 2 * GLOW_PAD,) * 2, Image.BILINEAR).point(lambda v: v // 2)
        sheet.paste(g, (x, 0))
        base = sheet.crop((x + GLOW_PAD, GLOW_PAD, x + GLOW_PAD + ICON, GLOW_PAD + ICON))
        sheet.paste(Image.composite(Image.new("L", ic.size, 255), base, ic), (x + GLOW_PAD, GLOW_PAD))
        sheet.paste(nm, (x, ICON + 2 * GLOW_PAD + 4))
    sheet.save(ROOT / "tools" / "tray_preview.png")
    print(f"{len(preview)} tray assets: icon {ICON}px, glow {GLOW_HALF}px (half res), names {NAME_PX}px")


if __name__ == "__main__":
    main()
