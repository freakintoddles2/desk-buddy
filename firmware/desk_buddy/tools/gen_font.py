#!/usr/bin/env python3
"""Make an LVGL 9 font (lv_font_fmt_txt, 4 bpp) from a TTF with Pillow.

Used for the big clock, which needs sizes above the built-in 48 px Montserrat. Only the
characters the clock needs are included. Digits get one shared advance width (tabular),
so the clock doesn't shift sideways as the time changes.

Usage: python3 tools/gen_font.py <size_px> [name] [chars] [--ttf FILE] [--slant S]
Writes src/<name>.c (default name: font_clock_<size>; default chars: the clock's).
  --ttf FILE  a font in tools/fonts (default Montserrat-Medium.ttf)
  --slant S   lean the glyphs right by S px per px of height (a fake italic, e.g. 0.12)
  --line H,B  line height and baseline (px from the bottom) instead of the font's own; a tall
              font like Anton has a 200+ px line at 140 px that would push Home's layout down
Examples:
  python3 tools/gen_font.py 88 font_temp_88 "-0123456789°"   (Weather's temperature)
  python3 tools/gen_font.py 120 font_heat_120 " .0123456789:" --ttf Anton-Regular.ttf --slant 0.12 --line 148,24
      (the Heat face's clock: same line height as font_clock_120, so Home's layout doesn't move)
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
args, opts = [], {}
it = iter(sys.argv[1:])
for a in it:
    if a.startswith("--"):
        opts[a[2:]] = next(it)
    else:
        args.append(a)
TTF = ROOT / "tools" / "fonts" / opts.get("ttf", "Montserrat-Medium.ttf")
SLANT = float(opts.get("slant", 0))
LINE = [int(v) for v in opts["line"].split(",")] if "line" in opts else None
SIZE = int(args[0])
NAME = args[1] if len(args) > 1 else f"font_clock_{SIZE}"
CHARS = "".join(sorted(args[2])) if len(args) > 2 else " .0123456789:"  # code-point order for the cmap ranges

font = ImageFont.truetype(str(TTF), SIZE)
ascent, descent = font.getmetrics()
line_height, base_line = LINE if LINE else (ascent + descent, descent)
digit_adv = max(font.getlength(c) for c in "0123456789")


def glyph(ch):
    adv = font.getlength(ch)
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    shift = 0
    if ch.isdigit():  # tabular: center the glyph in the shared advance
        shift = round((digit_adv - adv) / 2)
        adv = digit_adv
    if w == 0 or h == 0:
        return dict(adv=adv, w=0, h=0, ox=0, oy=0, px=b"")
    if not SLANT:
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        return dict(adv=adv, w=w, h=h, ox=x0 + shift, oy=-y1, px=img.tobytes())
    # Slanted: draw with room on both sides, shear about the baseline (rows above it move right),
    # then crop to what was drawn.
    pad = int(SLANT * max(abs(y0), abs(y1))) + 2
    img = Image.new("L", (w + 2 * pad, h), 0)
    ImageDraw.Draw(img).text((pad - x0, -y0), ch, font=font, fill=255, anchor="ls")
    img = img.transform(img.size, Image.AFFINE, (1, SLANT, SLANT * y0, 0, 1, 0), resample=Image.BICUBIC)
    bx0, by0, bx1, by1 = img.getbbox()
    img = img.crop((bx0, by0, bx1, by1))
    return dict(adv=adv, w=bx1 - bx0, h=by1 - by0, ox=x0 - pad + bx0 + shift, oy=-(y0 + by1), px=img.tobytes())


def pack4(px):
    nib = [v >> 4 for v in px]
    if len(nib) % 2:
        nib.append(0)
    return bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))


glyphs = [glyph(c) for c in CHARS]
bitmap = bytearray()
dscs = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,"]
for ch, g in zip(CHARS, glyphs):
    dscs.append(f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {round(g['adv'] * 16)}, .box_w = {g['w']}, "
                f".box_h = {g['h']}, .ofs_x = {g['ox']}, .ofs_y = {g['oy']}}} /* '{ch}' */,")
    bitmap += pack4(g["px"])

# cmap ranges: contiguous runs of code points
ranges, start = [], 0
for i in range(1, len(CHARS) + 1):
    if i == len(CHARS) or ord(CHARS[i]) != ord(CHARS[i - 1]) + 1:
        ranges.append((ord(CHARS[start]), i - start, start + 1))
        start = i

rows = [", ".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) for i in range(0, len(bitmap), 24)]
cap = font.getbbox("0", anchor="ls")
out = f"""/* Generated by tools/gen_font.py from {TTF.name} at {SIZE} px{f", slant {SLANT}" if SLANT else ""}, 4 bpp. Characters: "{CHARS}". Do not edit. */
#include <lvgl.h>

static const uint8_t glyph_bitmap[] = {{
  {(","+chr(10)+"  ").join(rows)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{chr(10).join(dscs)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
{chr(10).join(f"    {{.range_start = {a}, .range_length = {n}, .glyph_id_start = {g}, .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}," for a, n, g in ranges)}
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = {len(ranges)},
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {NAME} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {line_height},
    .base_line = {base_line},
    .cap_height = {-cap[1]},
    .x_height = {-cap[1]},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = 0,
    .underline_thickness = 0,
    .static_bitmap = 1,
    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};
"""
(ROOT / "src" / f"{NAME}.c").write_text(out)
print(f"{NAME}: {len(CHARS)} glyphs, {len(bitmap)} bytes, line height {line_height}")
