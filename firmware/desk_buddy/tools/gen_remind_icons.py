#!/usr/bin/env python3
"""Reminder card icons (stand, water, eyes) from ../../../mockups/reminder-mockups.html option B, as LVGL
A8 images (recolored per reminder). Same SVG subset and renderer as gen_icons.py.

Usage: python3 tools/gen_remind_icons.py   (writes src/remind_icons.c and src/remind_icons.h)
"""
import sys
from pathlib import Path

sys.argv = sys.argv[:1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_icons as gi  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SIZE = 64
SVGS = {
    "stand": '<svg viewBox="-3 -3 6 6"><circle class="ln" cx="0" cy="-2" r=".55"/><path class="ln" d="M 0 -1.3 V 0.6 M -1.2 -0.6 L 0 -1 L 1.2 -0.6 M 0 0.6 L -0.8 2.3 M 0 0.6 L 0.8 2.3"/></svg>',
    "water": '<svg viewBox="-3 -3 6 6"><path class="ln" d="M -1.5 -2.1 L -1.1 2.1 H 1.1 L 1.5 -2.1 Z M -1.3 -0.5 H 1.3"/></svg>',
    "eyes": '<svg viewBox="-3 -3 6 6"><path class="ln" d="M -2.5 0 C -1.2 -1.6 1.2 -1.6 2.5 0 C 1.2 1.6 -1.2 1.6 -2.5 0 Z"/><circle class="ln" r=".8"/></svg>',
}


def main():
    gi.SIZE = SIZE
    gi.STROKE = 0.38
    c = ["/* Generated by tools/gen_remind_icons.py. Do not edit. */", '#include "remind_icons.h"', ""]
    h = ["/* Generated by tools/gen_remind_icons.py. Do not edit. */", "#pragma once", "#include <lvgl.h>", "",
         "#ifdef __cplusplus", 'extern "C" {', "#endif"]
    for name, svg in SVGS.items():
        data = list(gi.render(svg).tobytes())
        rows = [", ".join(str(v) for v in data[r * SIZE:(r + 1) * SIZE]) for r in range(SIZE)]
        c.append(f"static const uint8_t remind_{name}_map[] = {{")
        c += [f"  {r}," for r in rows]
        c.append("};")
        c.append(f"const lv_image_dsc_t remind_{name} = {{")
        c.append(f"  .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = {SIZE}, .h = {SIZE}, .stride = {SIZE} }},")
        c.append(f"  .data_size = sizeof(remind_{name}_map),")
        c.append(f"  .data = remind_{name}_map,")
        c.append("};")
        c.append("")
        h.append(f"extern const lv_image_dsc_t remind_{name};")
    h += ["#ifdef __cplusplus", "}", "#endif", ""]
    (ROOT / "src" / "remind_icons.c").write_text("\n".join(c) + "\n")
    (ROOT / "src" / "remind_icons.h").write_text("\n".join(h))
    print(f"{len(SVGS)} reminder icons at {SIZE}px")


if __name__ == "__main__":
    main()
